#!/usr/bin/env python3
"""Independent finite checks for r021 fixed-root one-peak normalizers."""
import csv
import json
import math
from collections import Counter, defaultdict
from decimal import Decimal, getcontext
from pathlib import Path

getcontext().prec = 80
HERE = Path(__file__).resolve().parent

def graph(n):
    out = []
    for y in range(n):
        for x in range(n):
            a = set()
            for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
                X, Y = x+dx, y+dy
                if 0 <= X < n and 0 <= Y < n: a.add(Y*n+X)
            out.append(a)
    return out

def root_count_dp(n, root):
    adj = graph(n); N = n*n; full = (1 << N)-1
    dp = [0]*(1 << N); dp[0] = 1
    for S, c in enumerate(dp):
        if not c: continue
        rem = full ^ S
        while rem:
            bit = rem & -rem; rem ^= bit; v = bit.bit_length()-1
            if v == root or any((S >> z) & 1 for z in adj[v]):
                dp[S | bit] += c
    return dp[full]

def valid(word, adj):
    seen = set()
    for t, v in enumerate(word):
        if v in seen: return False
        if t and not (adj[v] & seen): return False
        seen.add(v)
    return True

def allowed(word, adj):
    seen = set(word)
    return sorted(set().union(*(adj[v] for v in word)) - seen) if word else list(range(len(adj)))

def prefix_states(n, root):
    adj = graph(n); by_depth = {1: {(root,)}}
    for r in range(1, n*n):
        nxt = set()
        for w in by_depth[r]:
            for v in allowed(w, adj): nxt.add(w+(v,))
        by_depth[r+1] = nxt
    return adj, by_depth

def check_prefix_support_and_kernel_n3():
    n=3; N=9; report={}
    for root in range(N):
        adj, levels = prefix_states(n, root)
        support_ok = True
        symmetric = True
        invariant = True
        per_depth = {}
        for r, states in levels.items():
            # Children generated by allowed() agree exactly with the enumerated support.
            if r < N:
                children={w+(v,) for w in states for v in allowed(w,adj)}
                support_ok &= children == levels[r+1]
            transition={}
            col=Counter()
            for w in states:
                c=Counter()
                for i in range(r):
                    for v in range(N):
                        y=list(w)
                        if v in y:
                            j=y.index(v)
                            y[i], y[j] = y[j], y[i]
                        else:
                            y[i]=v
                        y=tuple(y)
                        # This is precisely endpoint rejection for fixed root.
                        if y[0] != root or not valid(y,adj): y=w
                        c[y] += 1
                assert sum(c.values()) == r*N
                transition[w]=c
                col.update(c)
            invariant &= all(col[w] == r*N for w in states)
            for x,c in transition.items():
                for y, val in c.items():
                    symmetric &= val == transition[y][x]
            per_depth[str(r)]={"states":len(states),"row_sum":r*N,
                               "column_sum_uniform":all(col[w]==r*N for w in states)}
        report[str(root)]={"support_matches_allowed":support_ok,
                           "endpoint_rejection_kernel_symmetric":symmetric,
                           "uniform_fixed_root_prefix_invariant":invariant,
                           "depth":per_depth}
    return report

def read_exact(path):
    rows=[]
    for row in csv.DictReader(x for x in path.open() if not x.startswith("#")):
        rows.append(row)
    return {int(r["root"]):int(r["h_root"]) for r in rows}

def compare_exact():
    out={}
    for n in (3,4):
        got=read_exact(HERE/f"exact-n{n}-cpp.csv")
        want={r:root_count_dp(n,r) for r in range(n*n)}
        out[str(n)]={"all_roots_match_independent_subset_DP":got==want,
                     "counts":want,"total_A1":sum(want.values())}
        assert got==want
    return out

def summarize_calibrations():
    out={}
    for path in sorted(HERE.glob("cal-n*-root*-l*.csv")):
        meta=json.loads(Path(str(path)+".metadata.json").read_text())
        with path.open() as f: rows=list(csv.DictReader(f))
        n,root,P,R,L,T=(int(meta[k]) for k in ("n","root","P","R","L","threads"))
        assert len(rows)==R and {int(r["rep"]) for r in rows}==set(range(R))
        zs=[Decimal(r["Z"]) for r in rows]
        assert all(z.is_finite() and z>0 for z in zs)
        assert all(int(r["dead"])==0 for r in rows)
        # The rank-1 root is deterministic, and rank N is terminally sampled
        # without a move; MH runs precisely at ranks 2,...,N-1.
        assert all(int(r["proposals"])==P*L*(n*n-2) for r in rows)
        base=int(meta["seed_base"])
        for r in rows:
            rep=int(r["rep"])
            expected=(base+root*1000000007+rep*1009+L*1000003)%(1<<64)
            assert int(r["seed"])==expected
        total=sum(zs); mean=total/R
        target=Decimal(root_count_dp(n,root))
        se=(sum((z-mean)**2 for z in zs)/Decimal(R*(R-1))).sqrt()
        out[path.name]={"parameters":meta,"exact_h_root":str(target),
                        "mean_Z":str(mean),"delta_SE":str(se),
                        "relative_error":str(mean/target-1),
                        "replicate_weight_ESS":str(total*total/sum(z*z for z in zs)),
                        "max_replicate_weight_share":str(max(zs)/total),
                        "minimum_particle_parent_ESS":min(float(r["min_parent_ess"]) for r in rows)}
    return out

if __name__ == "__main__":
    result={"scope":"finite exact checks and finite SMC calibration only; no general mixing claim",
            "exact_root_counts":compare_exact(),
            "n3_prefix_support_and_endpoint_rejection_kernel":check_prefix_support_and_kernel_n3(),
            "calibrations":summarize_calibrations()}
    assert all(x["support_matches_allowed"] and x["endpoint_rejection_kernel_symmetric"] and x["uniform_fixed_root_prefix_invariant"] for x in result["n3_prefix_support_and_endpoint_rejection_kernel"].values())
    (HERE/"fixed-root-verification.json").write_text(json.dumps(result,indent=2)+"\n")
    print(json.dumps(result,indent=2))
