#!/usr/bin/env python3
"""Exact punctured-grid normalizer tables for the K=2 peak problem.

For each v of P_n square P_n this computes the two integer quantities

 A2_v = # {labellings with exactly two peaks and global maximum v},
 B_v  = # {the same, with the second-highest label outside N[v]}.

It uses C(I)=# {labellings in which every vertex of the independent set I
is a peak}.  C(I) is generated by the exact closed-neighbourhood recurrence.
The optional n=3 brute-force pass is deliberately independent of that
recurrence and of inclusion-exclusion.
"""

from __future__ import annotations

import argparse
import itertools
import json
from collections import defaultdict
from math import factorial
from pathlib import Path


def grid(n: int):
    N = n * n
    adj = [0] * N
    for y in range(n):
        for x in range(n):
            v = y * n + x
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                if 0 <= xx < n and 0 <= yy < n:
                    adj[v] |= 1 << (yy * n + xx)
    closed = [a | (1 << v) for v, a in enumerate(adj)]
    return N, adj, closed


def independent_sets_by_size(n: int):
    """Enumerate row-mask independent sets, grouped by cardinality."""
    rows = [r for r in range(1 << n) if not (r & (r << 1))]
    bags = defaultdict(list)

    def rec(y: int, previous: int, whole: int):
        if y == n:
            bags[whole.bit_count()].append(whole)
            return
        for r in rows:
            if not r & previous:
                rec(y + 1, r, whole | (r << (y * n)))

    rec(0, 0, 0)
    return bags


def closed_of(mask: int, adj: list[int]):
    ans = mask
    q = mask
    while q:
        bit = q & -q
        q ^= bit
        ans |= adj[bit.bit_length() - 1]
    return ans


def specified_peak_counts(n: int):
    """Return {I:C(I)} via the integral independent-peak recurrence."""
    N, adj, _ = grid(n)
    bags = independent_sets_by_size(n)
    C = {0: factorial(N)}
    closure = {0: 0}
    for k in range(1, (N + 1) // 2 + 1):
        for I in bags[k]:
            cl = closed_of(I, adj)
            closure[I] = cl
            numerator = 0
            q = I
            while q:
                bit = q & -q
                q ^= bit
                numerator += C[I ^ bit]
            den = cl.bit_count()
            assert numerator % den == 0, (n, I, numerator, den)
            C[I] = numerator // den
    return C, closure


def formula_table(n: int):
    N, adj, closed = grid(n)
    full = (1 << N) - 1
    C, closure = specified_peak_counts(n)
    anum = [0] * N
    bnum = [0] * N
    for I, count in C.items():
        k = I.bit_count()
        clI = closure[I]
        sign_a = 1 if k % 2 else -1  # (-1)^(k-1), harmless at k=0
        sign_b = 1 if k % 2 == 0 else -1  # (-1)^k
        for v in range(N):
            if I & closed[v]:
                continue
            if k:
                anum[v] += sign_a * k * count
            # for B, u is the prescribed rank-2 vertex after v; it must
            # avoid both N[v] and the closed neighbourhood of every I-peak.
            choices_u = (full & ~(closed[v] | clI)).bit_count()
            bnum[v] += sign_b * count * choices_u
    assert all(x % N == 0 for x in anum), (n, anum)
    assert all(x % (N * (N - 1)) == 0 for x in bnum), (n, bnum)
    A = [x // N for x in anum]
    B = [x // (N * (N - 1)) for x in bnum]
    return A, B, len(C)


def brute_n3():
    """Direct 9! check: no recurrence and no inclusion-exclusion."""
    n = 3
    N, adj, _ = grid(n)
    A = [0] * N
    B = [0] * N
    for order in itertools.permutations(range(N)):  # high label first
        pos = [0] * N
        for rank, v in enumerate(order):
            pos[v] = rank
        peaks = []
        for v in range(N):
            q = adj[v]
            if all(pos[v] < pos[u] for u in range(N) if (q >> u) & 1):
                peaks.append(v)
        if len(peaks) == 2:
            v, u = order[:2]
            A[v] += 1
            if not (adj[v] >> u) & 1:
                B[v] += 1
    return A, B


def render(n: int, direct_n3: bool):
    A, B, independent_count = formula_table(n)
    N = n * n
    out = {
        "n": n,
        "N": N,
        "independent_sets": independent_count,
        "A2_total": sum(A),
        "B_total": sum(B),
        "A2_over_B": {"numerator": sum(A), "denominator": sum(B)},
        "per_vertex": [],
    }
    for v, (a, b) in enumerate(zip(A, B)):
        out["per_vertex"].append({
            "v": v, "xy": [v % n, v // n], "degree": 4 - (v % n in (0, n - 1)) - (v // n in (0, n - 1)),
            "A2_v": a, "B_v": b,
            "B_over_A": {"numerator": b, "denominator": a},
        })
    assert sum(A) > 0 and sum(B) > 0
    if direct_n3 and n == 3:
        direct_a, direct_b = brute_n3()
        assert direct_a == A, (direct_a, A)
        assert direct_b == B, (direct_b, B)
        out["direct_9_factorial_crosscheck"] = "passed"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("n", type=int, choices=(3, 4, 5))
    ap.add_argument("--output", type=Path)
    ap.add_argument("--no-direct-n3", action="store_true")
    args = ap.parse_args()
    result = render(args.n, not args.no_direct_n3)
    encoded = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.write_text(encoded)
    else:
        print(encoded, end="")


if __name__ == "__main__":
    main()
