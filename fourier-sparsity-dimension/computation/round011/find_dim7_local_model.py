#!/usr/bin/env python3
"""Exact 16-atom, dimension-7 weighted-code obstruction for t=4."""
import argparse
import hashlib
import itertools
import json
import platform
import sys
from pathlib import Path

EDGES = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]


def fwht(a):
    a = a[:]
    h = 1
    while h < len(a):
        for p in range(0, len(a), 2 * h):
            for i in range(p, p + h):
                l, r = a[i], a[i + h]
                a[i], a[i + h] = l + r, l - r
        h *= 2
    return a


def val(mask, x):
    return sum(((mask >> j) & 1) * (((x >> a) & 1) * ((x >> b) & 1))
               for j, (a, b) in enumerate(EDGES)) & 1


def bent(mask):
    return {abs(z) for z in fwht([1 if val(mask, x) == 0 else -1 for x in range(16)])} == {4}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    B = {m for m in range(64) if bent(m)}
    # h1,h2,h1+h2 are a quadratic vectorial-bent pair.  Together with
    # RM(1,4) they give a [16,7] code of weights 0,6,8,10,16.
    h1, h2 = 12, 26  # x0x3+x1x2 ; x0x2+x1x2+x1x3
    # A={(x,h1(x),h2(x))} subset F2^6. Compute all its character sums.
    A = [x | (val(h1, x) << 4) | (val(h2, x) << 5) for x in range(16)]
    char_sums = [sum(1 if ((u & a).bit_count() & 1) == 0 else -1 for a in A)
                 for u in range(64)]
    # Code generated by 1,x0,...,x3,h1,h2: 128 words on the 16 atoms.
    weights = []
    for coeff in range(128):
        weights.append(sum(
            ((coeff & 1)
             ^ (((coeff >> 1) & x).bit_count() & 1)
             ^ (((coeff >> 5) & 1) * val(h1, x))
             ^ (((coeff >> 6) & 1) * val(h2, x)))
            for x in range(16)
        ))
    # A Boolean row with normalized spectrum supported on A and all
    # coefficients ±1/4 would be governed by a phase f on F_2^4 such that
    # f, f+h1, f+h2, f+h1+h2 are all bent.  Exhaust all 2^16 phases.
    compatible_f = []
    for fmask in range(1 << 16):
        good = True
        for combo in range(4):
            phase = [
                ((fmask >> x) & 1)
                ^ (((combo & 1) * val(h1, x)) ^ (((combo >> 1) & 1) * val(h2, x)))
                for x in range(16)
            ]
            if {abs(z) for z in fwht([1 if bit == 0 else -1 for bit in phase])} != {4}:
                good = False
                break
        if good:
            compatible_f.append(fmask)
    out = {
        "runtime": {
            "python": sys.version, "platform": platform.platform(),
            "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        },
        "edge_order": EDGES,
        "h1_mask": h1, "h2_mask": h2,
        "h1_h2_h1plus_h2_bent": all(x in B for x in (h1, h2, h1 ^ h2)),
        "atom_count": len(A), "atom_affine_span_rank": 6,
        "nontrivial_character_sum_set": sorted(set(char_sums[1:])),
        "atom_code_dimension": 7,
        "atom_code_weight_histogram": {str(w): weights.count(w) for w in sorted(set(weights))},
        "single_boolean_row_compatible_phase_count": len(compatible_f),
        "warning": ("This is a necessary-condition weighted-code model, not "
                    "a common-Hadamard/Walsh residual realization."),
    }
    assert out["atom_count"] == 16
    assert set(char_sums[1:]) <= {-4, 0, 4}
    assert sorted(set(weights)) == [0, 6, 8, 10, 16]
    assert not compatible_f
    with open(args.out, "w") as f:
        json.dump(out, f, indent=2, sort_keys=True)
    print(json.dumps(out, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
